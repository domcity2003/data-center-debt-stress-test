// Regenerates web/deal-data.js from data/deal.json so the page works from file://.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const deal = JSON.parse(readFileSync(join(root, "data/deal.json"), "utf8"));
const text = "// Generated by scripts/build_web_data.mjs from data/deal.json. Do not edit.\n" +
  "globalThis.dealData = " + JSON.stringify(deal, null, 2) + ";\n";
writeFileSync(join(root, "web/deal-data.js"), text);
console.log("wrote web/deal-data.js");
